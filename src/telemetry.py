from datetime import datetime
from typing import List
from pydantic import BaseModel, Field

class SysmonEvent(BaseModel):
    """
    Base schema for all Windows Sysmon events.
    Enforces standard fields required across all telemetry types.
    """
    timestamp: datetime = Field(
        ..., 
        description="Time the event was generated by the endpoint."
    )
    event_id: int = Field(
        ..., 
        description="Sysmon Event ID."
    )
    machine_name: str = Field(
        ..., 
        description="Hostname of the endpoint where the event occurred."
    )
    process_guid: str = Field(
        ..., 
        description="Unique global identifier for the process (Sysmon ProcessGuid)."
    )

class ProcessCreation(SysmonEvent):
    """
    Schema for Sysmon Event ID 1 (Process Creation).
    Captures execution details and process ancestry.
    """
    event_id: int = Field(1, frozen=True)
    image: str = Field(
        ..., 
        description="Absolute path to the executed image."
    )
    command_line: str = Field(
        ..., 
        description="Full command line used to execute the process."
    )
    parent_process_guid: str = Field(
        ..., 
        description="Unique global identifier of the parent process."
    )
    parent_image: str = Field(
        ..., 
        description="Absolute path to the parent executable image."
    )

class NetworkConnection(SysmonEvent):
    """
    Schema for Sysmon Event ID 3 (Network Connection).
    Captures outbound or inbound network traffic initiated by a process.
    """
    event_id: int = Field(3, frozen=True)
    destination_ip: str = Field(
        ..., 
        description="Target IP address of the connection."
    )
    destination_port: int = Field(
        ..., 
        description="Target port of the connection."
    )
    protocol: str = Field(
        ..., 
        description="Transport layer protocol."
    )

class InvestigationEpisode(BaseModel):
    """
    Aggregates a suspicious root process and all its related telemetry 
    within a bounded time window. This is the core unit passed to the 
    ML model and the Vertex AI Agent.
    """
    root_process_guid: str = Field(
        ..., 
        description="GUID of the process that triggered the initial security alert."
    )
    target_process: ProcessCreation = Field(
        ..., 
        description="The primary process creation event under investigation."
    )
    # Use default_factory for mutable lists to prevent shared state across instances
    related_processes: List[ProcessCreation] = Field(
        default_factory=list, 
        description="Child processes spawned within the observation window."
    )
    network_connections: List[NetworkConnection] = Field(
        default_factory=list, 
        description="Network connections initiated by the process tree."
    )